package gfx

import (
	"image/color"
	"unicode"
	"unicode/utf8"

	"github.com/hajimehoshi/ebiten/v2"
)

// Glyph dimensions of the built-in 3x5 pixel font.
const (
	GlyphW = 3
	GlyphH = 5
)

var glyphs = map[rune]*Bitmap{}

func init() {
	for r, rows := range glyphRows {
		glyphs[r] = NewBitmap(rows[:]...)
	}
}

// TextWidth returns the width in pixels of s drawn with DrawText.
func TextWidth(s string) int {
	n := utf8.RuneCountInString(s)
	if n == 0 {
		return 0
	}
	return n*(GlyphW+1) - 1
}

// DrawText draws s with the built-in font. Lowercase letters are drawn as uppercase.
func DrawText(dst *ebiten.Image, s string, x, y int, c color.Color) {
	for _, r := range s {
		if g := glyphs[unicode.ToUpper(r)]; g != nil {
			g.Draw(dst, x, y, c)
		}
		x += GlyphW + 1
	}
}

